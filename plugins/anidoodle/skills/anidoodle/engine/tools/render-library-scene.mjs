// Usage (from engine folder):
// node tools/render-library-scene.mjs --config /path/to/selected.json --allow-concept
// Builds a temporary native Film module and uses the unchanged Remotion/Chromium
// render backend. For a reference-only card, --allow-concept is required so the
// user knows the exact upstream animation has NOT been implemented here.
import {readFileSync,writeFileSync,rmSync} from "node:fs";
import {resolve,join,dirname} from "node:path";
import {spawnSync} from "node:child_process";
const opt=(x,def)=>{const i=process.argv.indexOf("--"+x);return i>=0?process.argv[i+1]:def};
const input=opt("config",null);
if(!input)throw Error("Required: --config /path/to/scene.json (exported from Library)");
const spec=JSON.parse(readFileSync(resolve(input),"utf8"));
if(spec.schema!=="persiandoodle/scene-selection/v1"||spec.locale!=="fa-IR")throw Error("Unsupported spec format");
if(!spec.text||typeof spec.text!=="string")throw Error("Missing scene text");
const references=(spec.implementation?.referenceComponents||[]).filter(x=>x);
if(references.length&&!process.argv.includes("--allow-concept")){
 throw Error("Selections not yet implemented as native cards: "+references.join(", ")+
  ". To render an ORIGINAL schematic interpretation, pass --allow-concept; otherwise port the selected cards first.");
}
const safe=(v,list,fallback)=>list.includes(v)?v:fallback;
const selections=spec.selections||{};
const raw=selections.background?.id?.split("/").at(-1);
const paper=safe(raw,["warm-paper","blueprint","parchment","night-ink","washi"],"warm-paper");
const pen=safe(selections.pen?.id?.split("/").at(-1),["qalam","fountain","pencil","marker","brush","none"],"qalam");
const name=selections.typography?.id||"";
const font=/(Vazirmatn|Estedad|Gandom|Shabnam|Lalezar|Samim|Sahel)/.exec(name)?.[1]||"Vazirmatn";
const entranceId=selections.entrance?.id||"";
const entrance=/fade|blur/.test(entranceId)?"fade":/slide|rise/.test(entranceId)?"slide":/pop|bounce/.test(entranceId)?"pop":"trace";
const cfg={title:"صحنهٔ طراحیِ اختصاصی",text:spec.text,paper,pen,font,entrance,withSound:selections.sound?.status!=="license-review"};
const generated=resolve("src/canvas-core/composedSelection.ts");
const out=resolve(opt("out","out/composed-selection.mp4"));
const still=resolve(opt("sheet","out/composed-selection-contact.jpg"));
const src=`// generated by render-library-scene.mjs; not source-controlled
import {makeComposedSceneFilm} from "./composedScene";
export const composedSelection=makeComposedSceneFilm(${JSON.stringify(cfg)});
`;
const run=(args)=>{const r=spawnSync(process.execPath,args,{stdio:"inherit"});if(r.error||r.status!==0)throw Error("scene renderer failed: "+args.join(" ")+": "+(r.error?.message||r.status));};
writeFileSync(generated,src);
try{
 run(["tools/still.mjs","composedSelection","--frames","25,65,105,160",
  "--sheet",still,"--out",resolve("out/composed-selection-stills")+"/"]);
 run(["tools/render.mjs","composedSelection","--out",out,"--workers","2"]);
 console.log("Native Persian film:",out,"\nContact sheet:",still);
 if(references.length)console.warn("CONCEPTUAL ONLY: external references need dedicated implementations:",references);
}finally{rmSync(generated,{force:true});}
